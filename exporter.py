"""
GNOME Theme Studio - Theme Packager & ZIP Exporter
Creates distributable archives ready to install on any GNOME Linux system.
"""

import os
import shutil
import zipfile

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
EXPORTS_DIR = os.path.join(SCRIPT_DIR, "exports")


def create_theme_zip(theme_name: str, compiled_dir: str) -> str:
    """
    Creates a zip archive containing the compiled theme and a standalone install script.
    Returns the absolute path to the generated .zip file.
    """
    os.makedirs(EXPORTS_DIR, exist_ok=True)
    zip_filename = f"{theme_name}.zip"
    zip_path = os.path.join(EXPORTS_DIR, zip_filename)

    if os.path.exists(zip_path):
        os.remove(zip_path)

    # Standalone quick installer to include inside the zip
    install_sh_content = f"""#!/usr/bin/env bash
# Standalone Theme Installer generated by GNOME Theme Studio
set -e
THEME_NAME="{theme_name}"
SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"

mkdir -p "$HOME/.themes/$THEME_NAME" "$HOME/.local/share/themes/$THEME_NAME"
cp -r "$SCRIPT_DIR/index.theme" "$SCRIPT_DIR/gnome-shell" "$SCRIPT_DIR/gtk-3.0" "$SCRIPT_DIR/gtk-4.0" "$HOME/.themes/$THEME_NAME/"
cp -r "$SCRIPT_DIR/index.theme" "$SCRIPT_DIR/gnome-shell" "$SCRIPT_DIR/gtk-3.0" "$SCRIPT_DIR/gtk-4.0" "$HOME/.local/share/themes/$THEME_NAME/"

# Apply GTK4 / Libadwaita
mkdir -p "$HOME/.config/gtk-4.0"
cp "$SCRIPT_DIR/gtk-4.0/gtk.css" "$HOME/.config/gtk-4.0/gtk.css"
cp "$SCRIPT_DIR/gtk-4.0/gtk-dark.css" "$HOME/.config/gtk-4.0/gtk-dark.css"

# Apply matching wallpaper if included
if [ -f "$SCRIPT_DIR/${THEME_NAME}-wallpaper.svg" ]; then
    mkdir -p "$HOME/.local/share/backgrounds"
    cp "$SCRIPT_DIR/${THEME_NAME}-wallpaper.svg" "$HOME/.local/share/backgrounds/"
    gsettings set org.gnome.desktop.background picture-uri "file://$HOME/.local/share/backgrounds/${THEME_NAME}-wallpaper.svg"
    gsettings set org.gnome.desktop.background picture-uri-dark "file://$HOME/.local/share/backgrounds/${THEME_NAME}-wallpaper.svg"
fi

# Apply Firefox theme if included
if [ -d "$SCRIPT_DIR/firefox" ]; then
    FF_DIRS=("$HOME/.config/mozilla/firefox" "$HOME/.mozilla/firefox" "$HOME/.var/app/org.mozilla.firefox/.mozilla/firefox" "$HOME/snap/firefox/common/.mozilla/firefox")
    for root in "${{FF_DIRS[@]}}"; do
        if [ -d "$root" ]; then
            for prof in "$root"/*; do
                if [ -d "$prof" ] && [[ "$prof" == *default* || -f "$prof/prefs.js" ]]; then
                    mkdir -p "$prof/chrome"
                    cp "$SCRIPT_DIR/firefox/userChrome.css" "$prof/chrome/" 2>/dev/null || true
                    cp "$SCRIPT_DIR/firefox/userContent.css" "$prof/chrome/" 2>/dev/null || true
                    touch "$prof/user.js"
                    if ! grep -q "toolkit.legacyUserProfileCustomizations.stylesheets" "$prof/user.js" 2>/dev/null; then
                        echo 'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);' >> "$prof/user.js"
                    fi
                fi
            done
        fi
    done
fi

# Apply via gsettings & dconf
gsettings set org.gnome.desktop.interface gtk-theme "$THEME_NAME"
gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark'
dconf write /org/gnome/shell/extensions/user-theme/name "''"
sleep 0.1
dconf write /org/gnome/shell/extensions/user-theme/name "'$THEME_NAME'"
echo "Theme $THEME_NAME installed and applied successfully!"
"""

    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zipf:
        # Add all files from compiled_dir under the root folder <theme_name>/
        for root, dirs, files in os.walk(compiled_dir):
            for file in files:
                abs_path = os.path.join(root, file)
                rel_path = os.path.relpath(abs_path, compiled_dir)
                archive_name = os.path.join(theme_name, rel_path)
                zipf.write(abs_path, archive_name)

        # Add install script inside root
        zipf.writestr(os.path.join(theme_name, "install.sh"), install_sh_content)

    return zip_path
