"""
GNOME Theme Studio - SCSS Compiler & Asset Processor Engine
Compiles GTK 3, GTK 4 / Libadwaita, and GNOME Shell 51 stylesheets using sassc.
"""

import os
import re
import time
import shutil
import subprocess

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
BASE_THEME_DIR = os.path.join(SCRIPT_DIR, "base_theme")
DEFAULT_BUILD_DIR = os.path.join(SCRIPT_DIR, "build")

# Original base theme accent colors in SVGs
ORIGINAL_ACCENT_PRIMARY = "#a7c080"
ORIGINAL_ACCENT_SECONDARY = "#83c092"


def sanitize_theme_name(name: str) -> str:
    """Sanitizes theme name for directory and GNOME Shell compatibility."""
    if not name or not name.strip():
        return "Studio-Theme"
    # Replace invalid chars with dashes, keep alphanumeric, dashes and underscores
    sanitized = re.sub(r"[^a-zA-Z0-9_\-]", "-", name.strip())
    sanitized = re.sub(r"-+", "-", sanitized)
    return sanitized.strip("-") or "Studio-Theme"


def generate_scss_variables(config: dict) -> tuple[str, str]:
    """Generates SCSS variable strings from frontend configuration dict."""
    accent_color = config.get("accent_color", "#a7c080")
    accent_fg = config.get("accent_fg", "#1a201c")
    accent_secondary = config.get("accent_secondary", "#83c092")
    window_bg = config.get("window_bg", "#2d353b")
    sidebar_bg = config.get("sidebar_bg", "#272e33")
    surface_elevated = config.get("surface_elevated", "#343f44")
    headerbar_bg = config.get("headerbar_bg", "#232a2e")
    text_primary = config.get("text_primary", "#d3c6aa")
    text_muted = config.get("text_muted", "#859289")
    border_color = config.get("border_color", "#3d484d")
    border_active = config.get("border_active", "#475258")

    destructive_color = config.get("destructive_color", "#e67e80")
    warning_color = config.get("warning_color", "#dbbc7f")
    info_color = config.get("info_color", "#7fbbb3")
    purple_color = config.get("purple_color", "#d699b6")
    orange_color = config.get("orange_color", "#e69875")

    # Metrics & Controls
    window_radius = int(config.get("window_radius", 12))
    button_radius = int(config.get("button_radius", 8))
    border_width = int(config.get("border_width", 1))
    panel_opacity = float(config.get("panel_opacity", 1.0))
    popup_radius = int(config.get("popup_radius", 20))
    quick_settings_radius = int(config.get("quick_settings_radius", 36))
    window_controls_size = int(config.get("window_controls_size", 14))
    window_controls_style = config.get("window_controls_style", "traffic-hover")

    color_scheme = config.get("color_scheme", "dark")
    gtk3_contained = (
        "resource:///org/gtk/libgtk/theme/Adwaita/gtk-contained.css"
        if color_scheme == "light"
        else "resource:///org/gtk/libgtk/theme/Adwaita/gtk-contained-dark.css"
    )

    vars_scss = f"""// Generated by GNOME Theme Studio
$accent-color:          {accent_color};
$accent-fg:             {accent_fg};
$accent-secondary:      {accent_secondary};
$window-bg:             {window_bg};
$sidebar-bg:            {sidebar_bg};
$surface-elevated:      {surface_elevated};
$headerbar-bg:          {headerbar_bg};
$text-primary:          {text_primary};
$text-muted:            {text_muted};
$border-color:          {border_color};
$border-active:         {border_active};

$destructive-color:     {destructive_color};
$warning-color:         {warning_color};
$info-color:            {info_color};
$purple-color:          {purple_color};
$orange-color:          {orange_color};

$color-scheme:          "{color_scheme}";
$window-controls-size:  {window_controls_size};
$window-controls-style: "{window_controls_style}";
$gtk3-contained-theme:  "{gtk3_contained}";
"""

    metrics_scss = f"""// Generated by GNOME Theme Studio Metrics
$window-radius:          {window_radius};
$button-radius:          {button_radius};
$border-width:           {border_width};
$panel-opacity:          {panel_opacity:.2f};
$popup-radius:           {popup_radius};
$quick-settings-radius:  {quick_settings_radius};
$window-controls-size:   {window_controls_size};
"""

    return vars_scss, metrics_scss


def process_svg_assets(src_shell_dir: str, dst_shell_dir: str, new_accent: str, new_secondary: str) -> list[str]:
    """Replaces hardcoded accent colors in SVGs and copies them to destination."""
    updated = []
    if not os.path.exists(src_shell_dir):
        return updated

    for filename in os.listdir(src_shell_dir):
        if filename.endswith(".svg"):
            src_path = os.path.join(src_shell_dir, filename)
            dst_path = os.path.join(dst_shell_dir, filename)

            with open(src_path, "r", encoding="utf-8") as f:
                content = f.read()

            # Case-insensitive replacement of original accent colors
            def repl_primary(match):
                return new_accent

            def repl_secondary(match):
                return new_secondary

            new_content = re.sub(re.escape(ORIGINAL_ACCENT_PRIMARY), repl_primary, content, flags=re.IGNORECASE)
            new_content = re.sub(re.escape(ORIGINAL_ACCENT_SECONDARY), repl_secondary, new_content, flags=re.IGNORECASE)

            with open(dst_path, "w", encoding="utf-8") as f:
                f.write(new_content)

            updated.append(filename)

    return updated


def generate_index_theme(theme_name: str, dst_path: str):
    """Generates index.theme metadata file."""
    content = f"""[Desktop Entry]
Type=X-GNOME-Metatheme
Name={theme_name}
Comment=Custom theme compiled by GNOME Theme Studio for GTK 3, GTK 4 & GNOME Shell 51
Encoding=UTF-8

[X-GNOME-Metatheme]
GtkTheme={theme_name}
MetacityTheme=Adwaita
IconTheme=Adwaita
CursorTheme=Adwaita
"""
    with open(dst_path, "w", encoding="utf-8") as f:
        f.write(content)


def compile_theme(config: dict, target_dir: str = None) -> dict:
    """
    Compiles full theme to target_dir.
    Returns status, timings, logs, and output directory path.
    """
    t_start = time.perf_counter()
    logs = []

    raw_name = config.get("theme_name", "Everforest-Studio")
    theme_name = sanitize_theme_name(raw_name)
    logs.append(f"Starting compilation for theme: '{theme_name}'")

    if not target_dir:
        target_dir = os.path.join(DEFAULT_BUILD_DIR, theme_name)

    logs.append(f"Target build directory: {target_dir}")

    # Create temporary build workspace
    workspace_dir = os.path.join(DEFAULT_BUILD_DIR, f".tmp_{theme_name}_{int(time.time()*1000)}")
    try:
        if os.path.exists(workspace_dir):
            shutil.rmtree(workspace_dir)

        # Structure directories
        os.makedirs(os.path.join(workspace_dir, "scss"), exist_ok=True)
        os.makedirs(os.path.join(workspace_dir, "gtk-4.0"), exist_ok=True)
        os.makedirs(os.path.join(workspace_dir, "gtk-3.0"), exist_ok=True)
        os.makedirs(os.path.join(workspace_dir, "gnome-shell"), exist_ok=True)
        os.makedirs(os.path.join(workspace_dir, "firefox"), exist_ok=True)

        # 1. Injected variables
        vars_scss, metrics_scss = generate_scss_variables(config)
        with open(os.path.join(workspace_dir, "scss", "_variables.scss"), "w", encoding="utf-8") as f:
            f.write(vars_scss)
        with open(os.path.join(workspace_dir, "scss", "_metrics.scss"), "w", encoding="utf-8") as f:
            f.write(metrics_scss)
        logs.append("SCSS dynamic variables and metrics injected.")

        # 2. Copy SCSS templates from immutable base_theme
        shutil.copy(os.path.join(BASE_THEME_DIR, "gtk-4.0", "gtk.scss"), os.path.join(workspace_dir, "gtk-4.0", "gtk.scss"))
        shutil.copy(os.path.join(BASE_THEME_DIR, "gtk-3.0", "gtk.scss"), os.path.join(workspace_dir, "gtk-3.0", "gtk.scss"))
        shutil.copy(os.path.join(BASE_THEME_DIR, "gnome-shell", "gnome-shell.scss"), os.path.join(workspace_dir, "gnome-shell", "gnome-shell.scss"))
        shutil.copy(os.path.join(BASE_THEME_DIR, "gnome-shell", "pad-osd.scss"), os.path.join(workspace_dir, "gnome-shell", "pad-osd.scss"))
        
        # Copy Firefox SCSS templates
        firefox_base_dir = os.path.join(BASE_THEME_DIR, "firefox")
        if os.path.exists(firefox_base_dir):
            for ff_file in ("userChrome.scss", "userContent.scss"):
                src_ff = os.path.join(firefox_base_dir, ff_file)
                if os.path.exists(src_ff):
                    shutil.copy(src_ff, os.path.join(workspace_dir, "firefox", ff_file))

        # 3. Compile each with sassc
        compilation_targets = [
            ("GTK 4 / Libadwaita", os.path.join(workspace_dir, "gtk-4.0", "gtk.scss"), os.path.join(workspace_dir, "gtk-4.0", "gtk.css")),
            ("GTK 3", os.path.join(workspace_dir, "gtk-3.0", "gtk.scss"), os.path.join(workspace_dir, "gtk-3.0", "gtk.css")),
            ("GNOME Shell 51", os.path.join(workspace_dir, "gnome-shell", "gnome-shell.scss"), os.path.join(workspace_dir, "gnome-shell", "gnome-shell.css")),
            ("Pad OSD", os.path.join(workspace_dir, "gnome-shell", "pad-osd.scss"), os.path.join(workspace_dir, "gnome-shell", "pad-osd.css"))
        ]

        # Add Firefox compilation if SCSS templates exist
        if os.path.exists(os.path.join(workspace_dir, "firefox", "userChrome.scss")):
            compilation_targets.append(
                ("Firefox userChrome", os.path.join(workspace_dir, "firefox", "userChrome.scss"), os.path.join(workspace_dir, "firefox", "userChrome.css"))
            )
        if os.path.exists(os.path.join(workspace_dir, "firefox", "userContent.scss")):
            compilation_targets.append(
                ("Firefox userContent", os.path.join(workspace_dir, "firefox", "userContent.scss"), os.path.join(workspace_dir, "firefox", "userContent.css"))
            )

        for label, scss_path, css_path in compilation_targets:
            t0 = time.perf_counter()
            cmd = ["sassc", scss_path, css_path]
            try:
                proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
            except FileNotFoundError:
                err_msg = "El compilador 'sassc' no está instalado en el sistema. Instálalo con: sudo dnf install sassc (Fedora) o sudo apt install sassc (Ubuntu/Debian)."
                logs.append(f"ERROR: {err_msg}")
                return {
                    "success": False,
                    "error": err_msg,
                    "logs": logs,
                    "theme_name": theme_name
                }
            if proc.returncode != 0:
                err_msg = f"Failed to compile {label}: {proc.stderr}"
                logs.append(f"ERROR: {err_msg}")
                return {
                    "success": False,
                    "error": err_msg,
                    "logs": logs,
                    "theme_name": theme_name
                }
            t_ms = (time.perf_counter() - t0) * 1000
            file_size_kb = os.path.getsize(css_path) / 1024
            logs.append(f"Compiled {label} -> {os.path.basename(css_path)} ({file_size_kb:.1f} KB in {t_ms:.1f}ms)")

        # 4. Copy dark variant imports
        shutil.copy(os.path.join(BASE_THEME_DIR, "gtk-4.0", "gtk-dark.css"), os.path.join(workspace_dir, "gtk-4.0", "gtk-dark.css"))
        shutil.copy(os.path.join(BASE_THEME_DIR, "gtk-3.0", "gtk-dark.css"), os.path.join(workspace_dir, "gtk-3.0", "gtk-dark.css"))

        # 5. Process and copy SVG assets with new accent colors
        new_accent = config.get("accent_color", "#a7c080")
        new_secondary = config.get("accent_secondary", "#83c092")
        updated_svgs = process_svg_assets(
            os.path.join(BASE_THEME_DIR, "gnome-shell"),
            os.path.join(workspace_dir, "gnome-shell"),
            new_accent,
            new_secondary
        )
        logs.append(f"Processed SVG assets with new accent ({new_accent}): {', '.join(updated_svgs)}")

        # 6. Generate index.theme
        generate_index_theme(theme_name, os.path.join(workspace_dir, "index.theme"))
        logs.append("Generated FreeDesktop index.theme metadata.")

        # 6.5. Generate matching wallpaper
        import wallpaper_generator
        wp_style = config.get("wallpaper_style", "abstract_waves")
        wp_filename = f"{theme_name}-wallpaper.svg"
        wp_path = os.path.join(workspace_dir, wp_filename)
        wallpaper_svg = wallpaper_generator.generate_svg_wallpaper(config, style=wp_style)
        with open(wp_path, "w", encoding="utf-8") as f:
            f.write(wallpaper_svg)
        logs.append(f"Generated matching 4K vector wallpaper ({wp_style}): {wp_filename}")

        # 7. Remove raw SCSS files from the final package
        shutil.rmtree(os.path.join(workspace_dir, "scss"), ignore_errors=True)
        for root, dirs, files in os.walk(workspace_dir):
            for file in files:
                if file.endswith(".scss"):
                    os.remove(os.path.join(root, file))

        # 8. Deploy to target_dir cleanly
        if os.path.exists(target_dir):
            shutil.rmtree(target_dir)
        shutil.copytree(workspace_dir, target_dir)

        duration_ms = (time.perf_counter() - t_start) * 1000
        logs.append(f"Compilation finished successfully in {duration_ms:.1f}ms.")

        return {
            "success": True,
            "theme_name": theme_name,
            "output_dir": target_dir,
            "duration_ms": round(duration_ms, 2),
            "logs": logs
        }

    finally:
        # Cleanup temporary workspace
        if os.path.exists(workspace_dir):
            shutil.rmtree(workspace_dir, ignore_errors=True)
